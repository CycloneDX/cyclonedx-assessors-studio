import { describe, it, expect } from 'vitest';
import {
  createReportDocument,
  drawTable,
  formatPercent,
  renderToBuffer,
  sectionHeading,
  stampFooters,
} from '../../utils/pdf-report.js';
import { countPdfPages, extractPdfPages } from '../helpers/pdf-text.js';

const COLUMNS = [
  { header: 'ID', width: 70 },
  { header: 'Name', width: 170 },
  { header: 'Result', width: 60 },
  { header: 'Rationale', width: 195 },
];

function longName(i: number): string {
  return `Requirement ${i} name that is long enough to wrap onto several lines inside its column`;
}

describe('formatPercent', () => {
  it('formats 0 as 0%, not N/A', () => {
    expect(formatPercent(0)).toBe('0%');
    expect(formatPercent('0')).toBe('0%');
  });

  it('rounds fractional scores to whole percentages', () => {
    expect(formatPercent(0.756)).toBe('76%');
    expect(formatPercent(1)).toBe('100%');
  });

  it('returns N/A only for missing or non-numeric scores', () => {
    expect(formatPercent(null)).toBe('N/A');
    expect(formatPercent(undefined)).toBe('N/A');
    expect(formatPercent('')).toBe('N/A');
    expect(formatPercent('abc')).toBe('N/A');
  });
});

describe('PDF report layout', () => {
  async function renderTable(rowCount: number): Promise<Buffer> {
    const doc = createReportDocument();
    sectionHeading(doc, 'Requirements');
    drawTable(
      doc,
      COLUMNS,
      Array.from({ length: rowCount }, (_, i) => [`REQ-${i}`, longName(i), 'YES', `Rationale ${i}`]),
    );
    stampFooters(doc, '2026-01-01T00:00:00.000Z');
    return renderToBuffer(doc);
  }

  it('draws every cell of a row on the same baseline', async () => {
    const pages = extractPdfPages(await renderTable(3));
    const items = pages[0].items;
    for (let i = 0; i < 3; i++) {
      const id = items.find((it) => it.text === `REQ-${i}`);
      const name = items.find((it) => it.text.startsWith(`Requirement ${i} name`));
      const result = items.filter((it) => it.text === 'YES')[i];
      const rationale = items.find((it) => it.text === `Rationale ${i}`);
      expect(id && name && result && rationale).toBeTruthy();
      expect(name!.y).toBe(id!.y);
      expect(result.y).toBe(id!.y);
      expect(rationale!.y).toBe(id!.y);
    }
  });

  it('gives wrapped rows their full height so rows do not overlap', async () => {
    const items = extractPdfPages(await renderTable(2))[0].items;
    const first = items.find((it) => it.text === 'REQ-0')!;
    const second = items.find((it) => it.text === 'REQ-1')!;
    // pdfkit flips the y axis, so later rows have a smaller y. The name
    // wraps to 2+ lines at 8.5pt, so the next row starts well below it.
    const firstNameLines = items.filter(
      (it) => it.y <= first.y && it.y > second.y && it.x === items.find((n) => n.text.startsWith('Requirement 0'))!.x,
    );
    expect(firstNameLines.length).toBeGreaterThanOrEqual(2);
    expect(first.y - second.y).toBeGreaterThan(firstNameLines.length * 9);
  });

  it('adds no blank pages and stamps a footer on each page', async () => {
    const pdf = await renderTable(60);
    const pageCount = countPdfPages(pdf);
    const pages = extractPdfPages(pdf);
    expect(pageCount).toBeGreaterThan(1);
    expect(pages).toHaveLength(pageCount);

    pages.forEach((page, i) => {
      expect(page.text).toContain(`Page ${i + 1} of ${pageCount}`);
      expect(page.text).toContain('Generated by CycloneDX Assessors Studio');
      // Each page carries table content besides the footer.
      expect(page.items.some((it) => it.text.startsWith('REQ-'))).toBe(true);
    });
  });

  it('repeats the table header on continuation pages', async () => {
    const pages = extractPdfPages(await renderTable(60));
    for (const page of pages) {
      expect(page.items.some((it) => it.text === 'Rationale')).toBe(true);
    }
  });
});
